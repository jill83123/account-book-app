/** Every synced entity carries these; deletions are tombstones so other devices learn of them. */
export interface Base {
  id: string
  updatedAt: number
  deleted?: boolean
}

export type AccountKind = 'cash' | 'bank' | 'card' | 'wallet'

export interface Account extends Base {
  name: string
  kind: AccountKind
  /** balance when the account was added; a card's owed amount is entered as a negative number */
  initial: number
  order: number
  color: string
  /** a bank logo as bank:<code>; missing means the default icon for its kind */
  icon?: string
  archived?: boolean
  /** left out of the asset totals (the account itself still shows) */
  excluded?: boolean
  /** a wallet in another currency: its balance is kept in that currency; rate = TWD worth of one unit (0 or missing: not known yet) */
  currency?: string
  rate?: number
  /** credit card only: day of month the statement closes / the bill is due */
  statementDay?: number
  dueDay?: number
}

export type CategoryKind = 'expense' | 'income'

export interface Category extends Base {
  name: string
  kind: CategoryKind
  /** null for a top-level category */
  parentId: string | null
  icon: string
  color: string
  order: number
  /** monthly budget, 0 or missing means none */
  budget?: number
  /** the first month (YYYY-MM) the default applies to; earlier months have no budget */
  budgetFrom?: string
  /** months (YYYY-MM) whose budget differs from the default */
  budgets?: Record<string, number>
  /** kept for the records that use it, but no longer offered when picking a category */
  hidden?: boolean
}

export interface Ledger extends Base {
  name: string
  order: number
  color: string
  /** the currency everything in this ledger is recorded in; missing means TWD */
  currency?: string
  /** TWD for one unit of `currency`, once known; missing until the trip is converted */
  rate?: number
  /** monthly budget for the whole ledger */
  budget?: number
  /** the first month (YYYY-MM) the default applies to; earlier months have no budget */
  budgetFrom?: string
  /** months (YYYY-MM) whose budget differs from the default */
  budgets?: Record<string, number>
}

/** One item of a record: a receipt with three products is one record with three lines. */
export interface Line {
  id: string
  name: string
  categoryId: string
  /** always in the main currency (TWD); a foreign price is converted when saved */
  amount: number
  /** the price as entered, when the record is in another currency */
  original?: number
  note?: string
  /** the parts of this item, as the person wrote them (a burger and a tea); they have no categories of their own */
  details?: { name: string; amount: number; /** how many, when it was noted */ qty?: number }[]
  /** spread this expense over this many months in reports (the cash still leaves on the date) */
  amortMonths?: number
}

export type RecordType = 'expense' | 'income' | 'transfer'

export interface Rec extends Base {
  type: RecordType
  /** YYYY-MM-DD */
  date: string
  /** HH:mm, or empty when no time was given (new records no longer ask for one) */
  time: string
  /** when the record was added (milliseconds); the time of day is no longer typed in */
  createdAt?: number
  ledgerId: string
  accountId: string
  /** transfers only */
  toAccountId?: string
  /** transfers into a wallet in another currency: the amount that arrived, in that currency */
  toTotal?: number
  merchantId?: string
  lines: Line[]
  /** sum of the lines (the amount for a transfer) */
  total: number
  /** set when the prices were entered in another currency: ISO code and how many TWD one unit is worth */
  currency?: string
  rate?: number
  note?: string
  /** generated by this recurring rule / installment plan */
  recurringId?: string
  /** where the record sits among the others of its day once they have been placed by hand (0 is the top) */
  pos?: number
  /** who the money was spent with (member ids) */
  companions?: string[]
  /** the bill was shared: `shares` are the other people's parts, so only the rest is this person's own spending */
  split?: {
    mode: 'even' | 'custom' | 'advance' | 'other'
    shares: { memberId: string; amount: number }[]
    /** `other`: the member who paid the whole bill; `mine` is what this person's own part came to, owed to them */
    payer?: string
    mine?: number
  }
  /** a balance adjustment: it moves the account's balance but is not income or spending, so reports leave it out */
  adjust?: boolean
}

export interface MerchantItem {
  name: string
  categoryId: string
  /** last price paid */
  price: number
  count: number
  lastUsed: string
}

export interface Merchant extends Base {
  name: string
  defaultCategoryId?: string
  defaultAccountId?: string
  items: MerchantItem[]
}

export type Freq = 'daily' | 'weekly' | 'monthly' | 'yearly'

export interface RecurringTemplate {
  type: RecordType
  accountId: string
  toAccountId?: string
  ledgerId: string
  merchantId?: string
  lines: Line[]
  note?: string
}

export interface Recurring extends Base {
  name: string
  kind: 'recurring' | 'installment'
  template: RecurringTemplate
  freq: Freq
  interval: number
  /** YYYY-MM-DD of the first occurrence */
  startDate: string
  endDate?: string
  /** how many occurrences in total (always set for an installment) */
  count?: number
  /** occurrences already handled (posted or skipped); the next one is occurrence number `generated` */
  generated: number
  /** true: post by itself when due; false: ask in the reminders */
  autoPost: boolean
  active: boolean
  installment?: { total: number; periods: number; fee: number }
}

export interface Repayment {
  id: string
  date: string
  amount: number
  accountId?: string
  note?: string
}

export interface Loan extends Base {
  direction: 'lend' | 'borrow'
  /** the member this is lent to / borrowed from */
  personId: string
  principal: number
  date: string
  dueDate?: string
  /** the account the money left from / arrived in; leave empty to keep it out of the balances */
  accountId?: string
  note?: string
  /** the record this was made from (a shared bill); it follows that record */
  recordId?: string
  repayments: Repayment[]
}

/**
 * A photo attached to a record. It is not one of the synced tables (nor in the JSON backup): the files travel
 * through Google Drive instead, see google/imageSync.ts. `synced` is set once Drive is known to hold it.
 */
export interface ImageRow {
  id: string
  recordId: string
  blob: Blob
  createdAt: number
  synced?: boolean
}

/** A photo that was removed here, remembered until its Drive copy is gone too. */
export interface ImageTrash {
  id: string
}

/** A person money is spent with or lent to. The name is only a label: everything else points at the id. */
export interface Member extends Base {
  name: string
}

export type TableName =
  | 'members'
  | 'accounts'
  | 'categories'
  | 'ledgers'
  | 'records'
  | 'merchants'
  | 'recurrings'
  | 'loans'

